  function seededRandom(seed) {
    var t = seed >>> 0;
    return function () {
      t += 0x6d2b79f5;
      var r = Math.imul(t ^ (t >>> 15), t | 1);
      r ^= r + Math.imul(r ^ (r >>> 7), r | 61);
      return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
    };
  }

  function buildBackgroundStars() {
    var rand = seededRandom(DATA.seed || 1729);
    var count = 1450;
    var position = new Float32Array(count * 3);
    var color = new Float32Array(count * 3);
    var size = new Float32Array(count);
    var phase = new Float32Array(count);
    var palette = [
      [0.72, 0.84, 1.0],
      [1.0, 0.95, 0.82],
      [0.86, 0.96, 1.0],
      [1.0, 0.82, 0.55]
    ];

    for (var i = 0; i < count; i++) {
      var radius = 26 + rand() * 40;
      var theta = Math.acos(2 * rand() - 1);
      var phi = rand() * Math.PI * 2;
      var sinTheta = Math.sin(theta);
      position[i * 3] = Math.cos(phi) * sinTheta * radius;
      position[i * 3 + 1] = 1.8 + Math.abs(Math.cos(theta)) * radius * 0.82;
      position[i * 3 + 2] = Math.sin(phi) * sinTheta * radius;
      var c = palette[Math.floor(rand() * palette.length)];
      var brightness = 0.45 + rand() * 0.55;
      color[i * 3] = c[0] * brightness;
      color[i * 3 + 1] = c[1] * brightness;
      color[i * 3 + 2] = c[2] * brightness;
      size[i] = 0.55 + Math.pow(rand(), 2.2) * 1.6;
      phase[i] = rand();
    }

    var geometry = new THREE.BufferGeometry();
    geometry.setAttribute('position', new THREE.BufferAttribute(position, 3));
    geometry.setAttribute('aColor', new THREE.BufferAttribute(color, 3));
    geometry.setAttribute('aSize', new THREE.BufferAttribute(size, 1));
    geometry.setAttribute('aPhase', new THREE.BufferAttribute(phase, 1));

    var material = new THREE.ShaderMaterial({
      transparent: true,
      depthWrite: false,
      depthTest: true,
      blending: THREE.AdditiveBlending,
      fog: false,
      uniforms: {
        uTime: timeUniform,
        uPixelRatio: pixelUniform
      },
      vertexShader: [
        'uniform float uTime;',
        'uniform float uPixelRatio;',
        'attribute vec3 aColor;',
        'attribute float aSize;',
        'attribute float aPhase;',
        'varying vec3 vColor;',
        'varying float vAlpha;',
        'void main() {',
        '  vec4 mv = modelViewMatrix * vec4(position, 1.0);',
        '  float twinkle = 0.62 + 0.38 * sin(uTime * 0.55 + aPhase * 31.4);',
        '  gl_PointSize = aSize * uPixelRatio * (58.0 / max(1.0, -mv.z)) * (0.75 + 0.4 * twinkle);',
        '  gl_Position = projectionMatrix * mv;',
        '  vColor = aColor;',
        '  vAlpha = 0.38 + 0.62 * twinkle;',
        '}'
      ].join('\n'),
      fragmentShader: [
        'varying vec3 vColor;',
        'varying float vAlpha;',
        'void main() {',
        '  vec2 p = gl_PointCoord - 0.5;',
        '  float d = length(p) * 2.0;',
        '  if (d > 1.0) discard;',
        '  float core = pow(1.0 - d, 3.0);',
        '  gl_FragColor = vec4(vColor * (0.55 + 1.2 * core), core * vAlpha);',
        '}'
      ].join('\n')
    });

    var points = new THREE.Points(geometry, material);
    points.renderOrder = -90;
    points.frustumCulled = false;
    scene.add(points);
    return points;
  }
