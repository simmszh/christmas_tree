  function triggerWish() {
    var rand = Math.random;
    for (var i = 0; i < WISH_COUNT; i++) {
      var theta = rand() * Math.PI * 2;
      var cosPhi = rand() * 2 - 1;
      var sinPhi = Math.sqrt(Math.max(0, 1 - cosPhi * cosPhi));
      var dx = Math.cos(theta) * sinPhi;
      var dy = cosPhi;
      var dz = Math.sin(theta) * sinPhi;
      var speed = 1.4 + Math.pow(rand(), 1.4) * 4.3;

      wishPositions[i * 3] = starPosition.x + dx * 0.12;
      wishPositions[i * 3 + 1] = starPosition.y + dy * 0.12;
      wishPositions[i * 3 + 2] = starPosition.z + dz * 0.12;
      wishVelocity[i * 3] = dx * speed;
      wishVelocity[i * 3 + 1] = dy * speed + 1.0;
      wishVelocity[i * 3 + 2] = dz * speed;
      wishAge[i] = 0;
      wishLife[i] = 1.55 + rand() * 1.55;
      wishSizes[i] = 1.4 + Math.pow(rand(), 2.0) * 3.4;
      wishAlphas[i] = 1;

      var c = wishPalette[Math.floor(rand() * wishPalette.length)];
      var warm = 0.75 + rand() * 0.35;
      wishColors[i * 3] = c[0] * warm;
      wishColors[i * 3 + 1] = c[1] * warm;
      wishColors[i * 3 + 2] = c[2] * warm;
    }
    wishGeometry.attributes.position.needsUpdate = true;
    wishGeometry.attributes.aColor.needsUpdate = true;
    wishGeometry.attributes.aSize.needsUpdate = true;
    wishGeometry.attributes.aAlpha.needsUpdate = true;
    wishActive = true;
    starPulse = 1;
    showToast();
    restartFlash();
  }

  function updateWish(dt) {
    if (!wishActive) return;
    var alive = false;
    for (var i = 0; i < WISH_COUNT; i++) {
      if (wishAge[i] >= wishLife[i]) {
        wishAlphas[i] = 0;
        continue;
      }
      alive = true;
      wishAge[i] += dt;
      var k = i * 3;
      wishVelocity[k + 1] -= 1.9 * dt;
      var drag = Math.pow(0.985, dt * 60);
      wishVelocity[k] *= drag;
      wishVelocity[k + 1] *= drag;
      wishVelocity[k + 2] *= drag;
      wishPositions[k] += wishVelocity[k] * dt;
      wishPositions[k + 1] += wishVelocity[k + 1] * dt;
      wishPositions[k + 2] += wishVelocity[k + 2] * dt;
      var lifeRatio = 1 - wishAge[i] / wishLife[i];
      wishAlphas[i] = Math.pow(Math.max(0, lifeRatio), 1.35);
    }
    wishGeometry.attributes.position.needsUpdate = alive;
    wishGeometry.attributes.aAlpha.needsUpdate = true;
    if (!alive) wishActive = false;
  }

